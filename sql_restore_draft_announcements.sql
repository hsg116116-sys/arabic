-- ── 1) تقرير: كل الإعلانات وحالتها ───────────────────────────────────────
SELECT
  left(title, 42)                                    AS العنوان,
  grade                                              AS الصف,
  CASE WHEN school = '' THEN 'كل المدارس' ELSE school END AS المدرسة,
  CASE WHEN published THEN 'منشور — يراه الطالب'
       ELSE 'مسودة — لا يراه الطالب' END               AS الحالة,
  left(coalesce(published_at::text, '—'), 16)         AS تاريخ_النشر
FROM public.announcements
ORDER BY published_at DESC NULLS LAST;

